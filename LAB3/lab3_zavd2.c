#include <stdio.h> // Підключення бібліотек
#include <math.h> // Підключення обчислень

int main() {
    int a, b, c, d; // Змінні

    printf("Введіть 4 цілих додатних числа: "); 
    scanf("%d %d %d %d", &a, &b, &c, &d);


    if (c == a + b && d == b + c) { // Якщо дорівнюють
        printf("Числа утворюють послідовність Фібоначчі\n");
    } else { // Якщо не дорівнюють
        printf("Числа не утворюють послідовність Фібоначчі\n");
    }

    return 0;
}
