#include <stdio.h> // Підключення Бібліотек
#include <math.h> // Підключення Обчислень
int main(void) {
    int n, m;

    // Зчитуємо розміри матриці
    printf("Введіть розміри матриці (n m): ");
    scanf("%d %d", &n, &m);

    // Оголошуємо двовимірний масив розміром n x m
    int a[n][m];

    // Заповнюємо матрицю з клавіатури поелементно
    printf("Введіть елементи матриці (%dx%d):\n", n, m);
    for (int i = 0; i < n; i++)          // цикл по рядках
        for (int j = 0; j < m; j++) {    // цикл по стовпцях
            printf("a[%d][%d] = ", i, j);
            scanf("%d", &a[i][j]);
        }

    // Виводимо матрицю на екран
    printf("\nМатриця A:\n");
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++)
            printf("%5d", a[i][j]);  // %5d — вирівнювання по ширині 5 символів
        printf("\n");                // переходимо на новий рядок після кожного рядка матриці
    }

    // Ініціалізуємо max та min першим елементом матриці
    int max = a[0][0];
    int min = a[0][0];

    // Шукаємо максимальний та мінімальний елементи одним проходом
    for (int i = 0; i < n; i++)
        for (int j = 0; j < m; j++) {
            if (a[i][j] > max) max = a[i][j];  // якщо елемент більший — оновлюємо max
            if (a[i][j] < min) min = a[i][j];  // якщо елемент менший — оновлюємо min
        }

    // Лічильники входжень max та min
    int count_max = 0;
    int count_min = 0;

    // Рахуємо скільки разів max та min зустрічаються в матриці
    for (int i = 0; i < n; i++)
        for (int j = 0; j < m; j++) {
            if (a[i][j] == max) count_max++;  // знайшли ще одне входження max
            if (a[i][j] == min) count_min++;  // знайшли ще одне входження min
        }

    // Виводимо результат
    printf("\nМаксимальний елемент: %d, кількість входжень: %d\n", max, count_max);
    printf("Мінімальний елемент: %d, кількість входжень: %d\n", min, count_min);

    return 0;
}
