#include <stdio.h> // Підключення бібліотек
#include <math.h> // Підключення Обчислень
int main(void) {
    int n, m;

    // Зчитуємо розміри матриці
    printf("Введіть розміри матриці (n m): ");
    scanf("%d %d", &n, &m);

    // Оголошуємо двовимірний масив розміром n x m
    int a[n][m];

    // Заповнюємо матрицю з клавіатури поелементно
    printf("Введіть елементи матриці (%dx%d):\n", n, m);
    for (int i = 0; i < n; i++)       // цикл по рядках
        for (int j = 0; j < m; j++) { // цикл по стовпцях
            printf("a[%d][%d] = ", i, j);
            scanf("%d", &a[i][j]);
        }

    // Виводимо матрицю на екран
    printf("\nМатриця A:\n");
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++)
            printf("%5d", a[i][j]); // %5d — вирівнювання по ширині 5 символів
        printf("\n");               // новий рядок після кожного рядка матриці
    }

    // Масиви для збереження унікальних значень та їх лічильників
    int unique[n * m];   // унікальні значення
    int count[n * m];    // кількість повторень кожного
    int size = 0;        // кількість унікальних елементів

    // Перебираємо всі елементи матриці
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            int val = a[i][j];
            int found = 0; // прапорець — чи вже зустрічали це значення

            // Шукаємо чи є вже таке значення серед унікальних
            for (int k = 0; k < size; k++) {
                if (unique[k] == val) {
                    count[k]++;  // якщо знайшли — збільшуємо лічильник
                    found = 1;
                    break;
                }
            }

            // Якщо значення нове — додаємо до масиву унікальних
            if (!found) {
                unique[size] = val;
                count[size] = 1;
                size++;
            }
        }
    }

    // Виводимо результат
    printf("\nКількість повторень елементів:\n");
    for (int k = 0; k < size; k++)
        printf("Значення %d зустрічається %d раз(и)\n", unique[k], count[k]);

    return 0;
}
