#include <stdio.h> // Підключення бібліотек
#include <math.h> // Підключення обчислень
int main() {
    int s = 0;

    for (int i = 1; i < 100; i++) {  // перебираємо числа від 1 до 100
        if (i % 11 == 0)  // якщо число кратне 11
            s += i;       // додаємо до суми
    }

    printf("Квадрат суми = %d\n", s * s);
    return 0;
}
