#include <stdio.h>  // підключення бібілотек
#include <math.h> // підключення обчислень
int main(void) {
    double x, y, x0, y0, x1, y1;

    // Зчитуємо значення x та y
    printf("Введіть x, y: ");
    scanf("%lf %lf", &x, &y);

    // Зчитуємо значення x0 та y0
    printf("Введіть x0, y0: ");
    scanf("%lf %lf", &x0, &y0);

    // Зчитуємо значення x1 та y1
    printf("Введіть x1, y1: ");
    scanf("%lf %lf", &x1, &y1);

    // Перевіряємо ділення на нуль
    if (x1 - x0 == 0 || y1 - y0 == 0) {
        printf("Помилка: ділення на нуль!\n");
        return 1;  // завершуємо програму з кодом помилки
    }

    // Обчислюємо вираз: (x - x0)/(x1 - x0) - (y - y0)/(y1 - y0)
    double result = (x - x0) / (x1 - x0) - (y - y0) / (y1 - y0);

    // Виводимо результат з точністю 4 знаки після коми
    printf("Результат = %.4f\n", result);

    return 0;
}
